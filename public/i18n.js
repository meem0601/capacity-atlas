export function normalizeLocale(value) {
  const locale = String(value || "").toLowerCase();
  return locale === "ja" || locale.startsWith("ja-") ? "ja" : "en";
}

function pluralize(template, params) {
  return template.replace(/\{(\w+), plural, one \{([^{}]*)\} other \{([^{}]*)\}\}/g, (_, key, one, other) => Number(params[key]) === 1 ? one : other);
}

export function translate(key, params = {}, locale = "ja") {
  const language = SUPPORTED_LOCALES.includes(locale) ? locale : normalizeLocale(locale);
  const template = MESSAGES[language][key] ?? MESSAGES.ja[key] ?? key;
  return pluralize(template, params).replace(/\{(\w+)\}/g, (_, name) => params[name] ?? `{${name}}`);
}

export function applyTranslations(root, locale) {
  root.querySelectorAll("[data-i18n]").forEach(element => {
    element.textContent = translate(element.dataset.i18n, {}, locale);
  });
  root.querySelectorAll("[data-i18n-aria]").forEach(element => {
    element.setAttribute("aria-label", translate(element.dataset.i18nAria, {}, locale));
  });
  root.querySelectorAll("[data-i18n-title]").forEach(element => {
    element.setAttribute("title", translate(element.dataset.i18nTitle, {}, locale));
  });
}
